export const countryBySlug = (slug: string): Place => {
  const c = countries.find((x) => x.slug === slug);
  if (!c) throw new Error("Unknown country: " + slug);
  return c;
};

export const hubs = countries.filter((c) => c.hub);

export const cityAsPlace = (citySlug: string): Place => {
  const parent = countryBySlug(cityParent[citySlug]);
  const name = cityNames[citySlug];
  return {
    ...parent,
    slug: citySlug,
    name,
    type: "city",
    countrySlug: parent.slug,
    countryName: parent.name,
    priceFactor: parent.priceFactor * 1.03,
    daysMin: Math.max(2, parent.daysMin - 1),
    daysMax: Math.max(3, parent.daysMax - 1),
    cities: [],
    localNote: cityNotes[citySlug],
    hub: false,
  };
};

